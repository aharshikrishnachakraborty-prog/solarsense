"""Write reports/model_card.md and the Phase 3 PNG charts from the computed results.

Every number in the card and charts comes from the metrics/table passed in.
"""

import matplotlib

matplotlib.use("Agg")   # draw charts straight to files (no window needed)
import matplotlib.dates  # noqa: E402
import matplotlib.pyplot as plt  # noqa: E402

from engine import config  # noqa: E402

MODEL_NAMES = {"physics": "Physics baseline (Model A)", "random_forest": "Random Forest (Model B)"}


def _score_rows(info):
    """Markdown table rows comparing both models for one plant."""
    rows = []
    for name, label in MODEL_NAMES.items():
        for part, part_label in [("test_all", "test days, all rows"),
                                 ("test_without_obvious_outages", "test days, outages excluded"),
                                 ("train", "training days")]:
            s = info[name][part]
            rows.append(f"| {label} | {part_label} | {s['mae_kw']} | {s['r2']} | {s['mape_pct']}% | {s['rows']:,} |")
    return rows


def write_model_card(metrics):
    """Write a beginner-friendly model card from the metrics dictionary."""
    lines = ["# Model card — expected-output model", "",
             "_Generated by `python -m engine.expected_model` — do not edit by hand._", "",
             "## What it does",
             "For every inverter and every 15 minutes of daylight, it predicts how much AC power the inverter "
             "**should** produce given the sunlight (irradiation), panel and air temperature and time of day. "
             "Comparing this **expected power** with the **actual power** is how we spot faults.", "",
             "## Data",
             "Kaggle \"Solar Power Generation Data\" (2 plants in India, 22 inverters each, 15-minute readings), "
             "cleaned in Phase 2. Only daylight rows with a real inverter reading are used for training/testing.", "",
             "**Time split (never random):** the model learns from the earlier days and is tested on later days "
             "it has never seen — just like real life, where we predict the future from the past.", ""]
    for plant in config.PLANTS:
        info = metrics[f"plant_{plant}"]
        coef = info["physics_coefficients"]
        lines += [f"## Plant {plant}", "",
                  f"- Training days: {info['train_dates'][0]} → {info['train_dates'][1]} ({info['train_days']} days, "
                  f"{info['train_rows']:,} rows).",
                  f"- Test days: {info['test_dates'][0]} → {info['test_dates'][1]} ({info['test_days']} days).",
                  f"- Obvious outages removed from training only: {info['train_outage_rows_removed']:,} rows "
                  f"(sunlight ≥ {metrics['settings']['outage_irradiation_min']} but output ≤ "
                  f"{metrics['settings']['outage_ac_max_kw']} kW). The test days keep "
                  f"{info['test_rows_obvious_outage']:,} such rows.",
                  f"- Physics formula fitted: k = {coef['k_kw_per_irradiation']} kW per unit of irradiation, "
                  f"γ = {coef['gamma_per_degC']} per °C.",
                  f"- **Chosen model: {MODEL_NAMES[info['chosen_model']]}** (lowest average error on test days).", "",
                  "| Model | Measured on | MAE (kW) | R² | MAPE | Rows |", "|---|---|---|---|---|---|"]
        lines += _score_rows(info)
        outage_share = 100 * info["test_rows_obvious_outage"] / info["random_forest"]["test_all"]["rows"]
        lines += ["", f"On the test days, **{outage_share:.1f}%** of readings are obvious outages (strong sun, "
                  "≈0 output). The model correctly predicts these *should* be producing, so they count as big "
                  "errors in \"all rows\" — that is why \"outages excluded\" is the fair measure of the model, "
                  "and why these rows matter for fault detection."]
        importance = ", ".join(f"{k} {v}" for k, v in info["rf_feature_importance"].items())
        lines += ["", f"Random Forest feature importance: {importance}.", ""]
    lines += ["## How to read the scores",
              "- **MAE** — on average, how many kW the prediction is off by. Lower is better.",
              "- **R²** — how much of the ups and downs in power the model explains. 1.0 = perfect, 0 = useless. "
              "Solar power follows sunlight very closely, so even a simple model scores high.",
              f"- **MAPE** — average error in %, only on rows where actual power ≥ "
              f"{metrics['settings']['mape_min_actual_kw']} kW (a % error on a tiny number would mislead).",
              "- \"Outages excluded\" shows how well the model describes **healthy** behaviour; \"all rows\" "
              "includes real faults on the test days, which the model is *supposed* to miss (that gap is what "
              "we detect).", "",
              "## Limitations (honest)",
              "- Only 34 days of data from one season (May–June): unknown accuracy in winter or monsoon.",
              "- One weather sensor per plant: a cloud over one part of the plant looks like a fault there. "
              "Peer comparison (each inverter vs the plant median) reduces this.",
              "- The Random Forest learns each inverter's \"normal\" from the training days. If an inverter was "
              "already degraded then, the model treats that as normal.",
              "- Random Forests cannot predict beyond what they saw (e.g. sunlight stronger than any training day).",
              "- Plant 1 DC values were rescaled (see assumptions.md); the models predict AC power, which was not "
              "rescaled.", ""]
    config.MODEL_CARD.write_text("\n".join(lines), encoding="utf-8")


def _healthy_day_chart(table, plant):
    """Plant-total actual vs expected on the test day where the plant matched expectations best."""
    test = table[(table["plant"] == plant) & (table["split"] == "test") & (~table["is_missing"])]
    daily = test.groupby("date")[["ac_kw", "expected_kw"]].sum()
    day = (daily["ac_kw"] / daily["expected_kw"] - 1).abs().idxmin()
    one_day = test[test["date"] == day].groupby("timestamp")[["ac_kw", "expected_kw"]].sum() / 1000

    fig, ax = plt.subplots(figsize=(9, 4.5))
    ax.plot(one_day.index, one_day["ac_kw"], label="Actual", color="#1f77b4", linewidth=2)
    ax.plot(one_day.index, one_day["expected_kw"], label="Expected (model)", color="#f59e0b",
            linewidth=2, linestyle="--")
    ax.set_title(f"Plant {plant}, {day} (test day): actual output follows the model's expectation")
    ax.set_xlabel("Time of day")
    ax.set_ylabel("Plant AC power (MW)")
    ax.xaxis.set_major_formatter(matplotlib.dates.DateFormatter("%H:%M"))
    ax.legend()
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(config.FIGURES_DIR / "expected_vs_actual_healthy_day.png", dpi=120)
    plt.close(fig)
    return day


def _scatter_chart(table, metrics):
    """Predicted vs actual for every test row, one panel per plant."""
    fig, axes = plt.subplots(1, len(config.PLANTS), figsize=(11, 5))
    for ax, plant in zip(axes, config.PLANTS):
        test = table[(table["plant"] == plant) & (table["split"] == "test") & (~table["is_missing"])]
        sample = test.sample(n=min(5000, len(test)), random_state=config.RANDOM_SEED)
        info = metrics[f"plant_{plant}"]
        r2 = info[info["chosen_model"]]["test_all"]["r2"]
        ax.scatter(sample["expected_kw"], sample["ac_kw"], s=4, alpha=0.3, color="#1f77b4")
        top = max(sample["expected_kw"].max(), sample["ac_kw"].max())
        ax.plot([0, top], [0, top], color="#f59e0b", linewidth=2, label="Perfect prediction")
        ax.set_title(f"Plant {plant} test days — R² = {r2}")
        ax.set_xlabel("Expected AC power (kW)")
        ax.set_ylabel("Actual AC power (kW)")
        ax.legend(loc="upper left")
        ax.grid(alpha=0.3)
    fig.suptitle("Most points sit on the line; points far below it are possible faults")
    fig.tight_layout()
    fig.savefig(config.FIGURES_DIR / "predicted_vs_actual_scatter.png", dpi=120)
    plt.close(fig)


def make_figures(table, metrics):
    """Export the two Phase 3 charts to reports/figures/."""
    config.FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    metrics["figure_healthy_day"] = _healthy_day_chart(table, plant=1)
    _scatter_chart(table, metrics)
